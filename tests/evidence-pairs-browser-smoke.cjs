"use strict";
const {chromium}=require("playwright"),assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path"),url=require("node:url");
const output=path.resolve("evidence-pairs-ui-review");fs.mkdirSync(output,{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true}),jsErrors=[],remote=[];
 try{
  const context=await browser.newContext({viewport:{width:1280,height:720}});
  const page=await context.newPage();page.on("pageerror",e=>jsErrors.push(e.message));
  page.on("request",req=>{if(/^https?:/.test(req.url()))remote.push(req.url());});
  page.on("dialog",d=>d.accept());
  await page.goto(url.pathToFileURL(path.resolve("evidence-pairs-case04.html")).href,{waitUntil:"load"});
  const card=name=>page.locator(".evidence-card").filter({hasText:name});
  const shot=async name=>page.screenshot({path:path.join(output,name),fullPage:true});
  assert.equal(await page.locator(".evidence-card").count(),6);
  assert.equal(await page.locator(".question.done").count(),0);
  assert.equal(await page.locator("#progress").innerText(),"0 / 3");
  await shot("01-1280-opening.png");
  await card("紙の発注書").click();
  await card("代理承認の規程").click();
  assert.equal(await page.locator(".evidence-card.open").count(),2);
  await page.locator("#connect").click();
  assert.equal(await page.locator("#progress").innerText(),"0 / 3");
  assert.equal(await page.locator(".evidence-card.open").count(),2,"wrong match must not hide information");
  assert.match(await page.locator("#feedback").innerText(),/減点はありません/);
  await shot("02-1280-wrong-pair-no-penalty.png");
  await card("紙の発注書").click();await card("電子発注台帳").click();await page.locator("#connect").click();
  assert.equal(await page.locator("#progress").innerText(),"1 / 3");
  assert.equal(await page.locator(".question.done").count(),1);
  await shot("03-1280-first-connection.png");
  await page.locator('[data-tab="notes"]').click();
  assert.equal(await page.locator('[data-screen="notes"]').isVisible(),true);
  assert.equal(await page.locator('[data-screen="board"]').isVisible(),false);
  assert.match(await page.locator("#findings").innerText(),/EVT-044/);
  await page.locator('[data-tab="board"]').click();
  await card("発注登録ログ").click();await card("電子承認ログ").click();await page.locator("#connect").click();
  assert.equal(await page.locator("#progress").innerText(),"2 / 3");
  await card("代理承認の規程").click();await card("承認者の電子署名").click();await page.locator("#connect").click();
  assert.equal(await page.locator("#progress").innerText(),"3 / 3");
  assert.equal(await page.locator(".question.done").count(),3);
  await shot("04-1280-all-evidence-connected.png");
  await page.locator('[data-tab="report"]').click();
  assert.equal(await page.locator('[data-screen="report"]').isVisible(),true);
  assert.equal(await page.locator('[data-verdict="clear"]').isEnabled(),true);
  await page.locator('[data-verdict="clear"]').click();
  assert.match(await page.locator("#finalReport").innerText(),/正式な電子代理承認/);
  assert.match(await page.locator("#finalReport").innerText(),/23分前/);
  await shot("05-1280-verdict-explained.png");
  const small=await browser.newContext({viewport:{width:1024,height:768}});
  const smallPage=await small.newPage();smallPage.on("pageerror",e=>jsErrors.push(e.message));
  await smallPage.goto(url.pathToFileURL(path.resolve("evidence-pairs-case04.html")).href,{waitUntil:"load"});
  assert.equal(await smallPage.locator(".evidence-card").count(),6);
  await smallPage.screenshot({path:path.join(output,"06-1024-opening.png"),fullPage:true});
  assert.deepEqual(jsErrors,[]);assert.deepEqual(remote,[]);
  const record={status:"PASS",cardCount:6,questionsResolved:3,wrongPairRetainsCards:true,sourceProbability:"none",tabSwitch:true,verdict:"clear",screenshots:6,viewports:["1280x720","1024x768"],consolePageErrors:jsErrors,remoteRequests:remote,scope:"Chromium local HTML. NOT Electron MSIX install QA."};
  fs.writeFileSync(path.join(output,"EVIDENCE_PAIRS_QA.json"),JSON.stringify(record,null,2)+"\n");
  console.log("EVIDENCE_PAIRS_BROWSER_PASS "+JSON.stringify(record));
 }finally{await browser.close();}
})().catch(err=>{console.error(err.stack);process.exitCode=1;});
